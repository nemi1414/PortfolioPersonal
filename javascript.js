const formStatus = document.getElementById('form-status');
const submitButton = form.querySelector('button[type="submit"]');

form.addEventListener('submit', function(event) {
    event.preventDefault();
    formStatus.textContent = translations[currentLanguage].sending;
    submitButton.disabled = true;

    emailjs.sendForm('service_vneod7q', 'template_545vbv9', form)
        .then(function() {
            formStatus.textContent = translations[currentLanguage].sent;
            form.reset();
        })
        .catch(function(error) {
            console.error('No se pudo enviar el mensaje de contacto.', error);
            formStatus.textContent = translations[currentLanguage].sendError;
        })
        .finally(function() {
            submitButton.disabled = false;
        });
});

